#Realizar la carga del lado de un cuadrado, mostrar por 
#pantalla el perímetro del mismo (El perímetro de un cuadrado 
#se calcula multiplicando el valor del lado por cuatro)
cadena = input("Ingrese el valor del lado del cuadrado: ")
lado = int(cadena)
perimetro = lado * 4
print("El perímetro del cuadrado es: ", perimetro)